// Cardboard 1.4.0's GUI save projection P = fm∘sv, cut out of the editor store's bundle (installErrorTelemetry-*.js)
// at build time: what the editor can represent of a timeline item, with its times rounded to 0.1 s (`ho`, `nx`, `sv`)
// and its caption style keys (`x2`, `Vb`). The adapter diffs a GUI save through it (B3, B10, PLAN §4.3), so an agent's
// frame-accurate times and the fields the editor doesn't know survive a person's unrelated edit. It is Cardboard's
// own code, so it is taken from the bundle rather than written again; if a piece moves, the build stops here.
// `Cy` is a zod schema for fades; the projection only needs it to pass a valid fade through.
// Usage: require("./fmsv").source(bundleText) → a CommonJS module's text exporting the item projection.
const block = (src, start, open, close) => {
  const i = src.indexOf(start);
  if (i < 0 || src.indexOf(start, i + 1) >= 0) throw new Error(`fmsv: expected one ${JSON.stringify(start)}`);
  let j = i + start.length - 1, depth = 0;
  if (src[j] !== open) throw new Error(`fmsv: ${JSON.stringify(start)} must end with ${open}`);
  for (; j < src.length; j++) {
    if (src[j] === open) depth++;
    else if (src[j] === close && --depth === 0) break;
  }
  return src.slice(i, j + 1);
};

exports.source = (src) => {
  const ho = "ho=t=>Math.round(t*10)/10";
  if (!src.includes(ho)) throw new Error("fmsv: no ho");
  const nx = block(src, "nx=t=>{", "{", "}");
  const sv = block(src, "sv=t=>{", "{", "}");
  const x2 = block(src, "x2=[", "[", "]");
  const vb = block(src, "Vb=t=>{", "{", "}");
  const items = block(src, "timelineItems:t.timelineItems?.map(e=>(", "(", ")");
  const body = items.slice(items.indexOf("e=>(") + 3);
  return [
    "// Generated by scripts/carton/fmsv.js from Cardboard 1.4.0's editor bundle: its GUI save projection.",
    "const Cy={safeParse:(d)=>d&&typeof d===\"object\"&&typeof d.duration===\"number\"?{success:!0,data:d}:{success:!1}};",
    `const ${ho},${nx},${sv},${x2},${vb};`,
    `module.exports=(e)=>JSON.parse(JSON.stringify(${body}));`,
    "",
  ].join("\n");
};
