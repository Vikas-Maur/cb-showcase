// Cardboard's GUI save projection P = fm∘sv, cut out of the editor store's bundle (installErrorTelemetry-*.js) at
// build time: what the editor can represent of a timeline item, with its times rounded to 0.1 s (1.4.0's `ho`, `nx`,
// `sv`) and its caption style keys (`x2`, `Vb`). The adapter diffs a GUI save through it (B3, B10, PLAN §4.3), so an
// agent's frame-accurate times and the fields the editor doesn't know survive a person's unrelated edit. It is
// Cardboard's own code, so it is taken from the bundle rather than written again; if a piece moves, the build stops here.
// `Cy` is a zod schema for fades; the projection only needs it to pass a valid fade through.
// The pieces are found by where the item projection calls them (its `...sv(e)` after trackId and `...Vb(e)` after
// captionSegments, then what those call), not by their minified names, which change with each Cardboard release
// (1.5.0: fo, tx, iv, _2, zb; the fade schema Py).
// Usage: require("./fmsv").source(bundleText) → a CommonJS module's text exporting the item projection.
const block = (src, start, open, close) => {
  const i = src.indexOf(start);
  if (i < 0 || src.indexOf(start, i + 1) >= 0) throw new Error(`fmsv: expected one ${JSON.stringify(start)}`);
  let j = i + start.length - 1, depth = 0;
  if (src[j] !== open) throw new Error(`fmsv: ${JSON.stringify(start)} must end with ${open}`);
  for (; j < src.length; j++) {
    if (src[j] === open) depth++;
    else if (src[j] === close && --depth === 0) break;
  }
  return src.slice(i, j + 1);
};

const named = (text, re, what) => {
  const m = re.exec(text);
  if (!m) throw new Error(`fmsv: no ${what}`);
  return m[1];
};

exports.source = (src) => {
  const items = block(src, "timelineItems:t.timelineItems?.map(e=>(", "(", ")");
  const body = items.slice(items.indexOf("e=>(") + 3);
  const N = "([\\w$]+)";
  const svName = named(body, new RegExp(`trackId:e\\.trackId,\\.\\.\\.${N}\\(e\\),`), "item times (sv)");
  const vbName = named(body, new RegExp(`captionSegments:e\\.captionSegments,\\.\\.\\.${N}\\(e\\),`), "caption style (Vb)");
  const sv = block(src, `${svName}=t=>{`, "{", "}");
  const hoName = named(sv, new RegExp(`const e=${N}\\(Math\\.max\\(0,t\\.startTime`), "rounding (ho)");
  const nxName = named(sv, new RegExp(`audioFadeIn:${N}\\(t\\.audioFadeIn\\)`), "fade (nx)");
  const ho = `${hoName}=t=>Math.round(t*10)/10`;
  if (!src.includes(ho)) throw new Error(`fmsv: no ${ho}`);
  const nx = block(src, `${nxName}=t=>{`, "{", "}");
  const cyName = named(nx, new RegExp(`const e=${N}\\.safeParse\\(t\\)`), "fade schema (Cy)");
  const vb = block(src, `${vbName}=t=>{`, "{", "}");
  const x2Name = named(vb, new RegExp(`for\\(const n of ${N}\\)`), "caption keys (x2)");
  const x2 = block(src, `${x2Name}=[`, "[", "]");
  return [
    "// Generated by scripts/carton/fmsv.js from Cardboard's editor bundle: its GUI save projection.",
    `const ${cyName}={safeParse:(d)=>d&&typeof d===\"object\"&&typeof d.duration===\"number\"?{success:!0,data:d}:{success:!1}};`,
    `const ${ho},${nx},${sv},${x2},${vb};`,
    `module.exports=(e)=>JSON.parse(JSON.stringify(${body}));`,
    "",
  ].join("\n");
};
