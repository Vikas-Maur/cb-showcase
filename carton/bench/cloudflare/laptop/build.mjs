// Bundles laptop.ts (with Carton's client code it imports) into ONE .mjs that a person runs with `node` on their own
// machine (Windows included, Node >= 22.3: global WebSocket and fetch, process.getBuiltinModule). The bundle imports
// nothing but Node's built-ins, and the build refuses one that would: an npm import, `node:sqlite` (flagged before
// Node 22.13), or anything that names the lab's secrets.
//
//   node bench/cloudflare/laptop/build.mjs        (from carton/; esbuild comes from carton/node_modules)
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, statSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const CARTON = join(HERE, "..", "..", "..");
const OUT_DIR = process.env.CF_LAB_LAPTOP_OUT ?? "/home/ubuntu/.t3/projects/cardboard-showcase/_inspect/carton-build/cf-lab/laptop";
const out = join(OUT_DIR, "cf-lab-laptop.mjs");

const git = (...a) => {
  try {
    return execFileSync("git", a, { cwd: CARTON, encoding: "utf8" }).trim();
  } catch {
    return null;
  }
};
const info = {
  commit: git("rev-parse", "--short=12", "HEAD"),
  branch: git("rev-parse", "--abbrev-ref", "HEAD"),
  // what the bundle is made of and no commit has: edits to committed files, and new files
  dirty: !!git("status", "--porcelain", "--untracked-files=no", "--", "packages", "bench/cloudflare"),
  untracked: (git("status", "--porcelain", "--untracked-files=all", "--", "packages", "bench/cloudflare") ?? "").split("\n").some((l) => l.startsWith("??")),
  builtAt: new Date().toISOString(),
  // whether this build's WebSocket transport closes a link whose keepalive goes unanswered (fix/cf-dead-link)
  transportDeadLink: readFileSync(join(CARTON, "packages/server-node/src/transport.ts"), "utf8").includes("deadAfterMs"),
};

mkdirSync(OUT_DIR, { recursive: true });
const r = await build({
  entryPoints: [join(HERE, "laptop.ts")],
  outfile: out,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  // readable on purpose: whoever runs it can see what it does
  minify: false,
  legalComments: "none",
  metafile: true,
  logLevel: "warning",
  define: { CF_LAB_BUILD: JSON.stringify(info) },
  banner: { js: `// cf-lab-laptop: the Carton lab's network test (generated by carton/bench/cloudflare/laptop/build.mjs, ${info.commit}${info.dirty ? "+dirty" : ""}).\n// Run: node cf-lab-laptop.mjs config.json` },
});

const builtins = new Set(builtinModules.flatMap((m) => [m, `node:${m}`]));
const imports = Object.values(r.metafile.outputs).flatMap((o) => o.imports);
const foreign = imports.filter((i) => !builtins.has(i.path));
if (foreign.length) throw new Error(`the bundle imports more than Node's built-ins: ${[...new Set(foreign.map((i) => i.path))].join(", ")}`);
if (imports.some((i) => i.path === "node:sqlite" || i.path === "sqlite")) throw new Error("the bundle imports node:sqlite (flagged before Node 22.13)");
const text = readFileSync(out, "utf8");
for (const bad of ["carton-lab-secrets", "AUTH_SECRET", "ADMIN_TOKEN", "carton-cf-token"]) if (text.includes(bad)) throw new Error(`the bundle mentions ${bad}`);

const inputs = Object.keys(r.metafile.inputs).length;
console.log(`${out}\n  ${(statSync(out).size / 1024).toFixed(1)} KiB, ${inputs} source files, imports only: ${[...new Set(imports.map((i) => i.path))].sort().join(" ")}`);
console.log(`  build ${JSON.stringify(info)}`);
